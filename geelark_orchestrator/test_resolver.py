def _row(**overrides):
    base = {
        "profile_key": "Test_01",
        "geelark_profile_id": "GL-TEST",
        "business_name": "Test Biz",
        "home_lat": "51.5",
        "home_lng": "-0.12",
        "business_lat": "51.501",
        "business_lng": "-0.088",
        "nearby_points": "51.5224,-0.1026|51.5187,-0.0991",
        "nearby_points_backup": "51.5198,-0.1011",
        "branded_keywords": "Test Biz near me",
        "search_keywords": "thing one|thing two|thing three",
        "business_goal": "review",
        "profile_verdict": "pending",
        "provisioned": "false",
        "maps_verified": "false",
    }
    base.update(overrides)
    return base


# ---------- Two-delimiter rule: the coordinate must never be torn ----------

def test_coord_stays_intact_through_parsing():
    p = profile_from_row(_row())
    # Two points, each with its lat,lng glued together.
    assert len(p.nearby_points) == 2
    assert p.nearby_points[0].lat == 51.5224
    assert p.nearby_points[0].lng == -0.1026
    # The token round-trips with the comma inside.
    assert p.nearby_points[0].as_token() == "51.5224,-0.1026"


def test_pipe_separates_comma_does_not():
    pool = _split_pool("51.5224,-0.1026|51.5187,-0.0991|51.5203,-0.1044")
    assert pool == ["51.5224,-0.1026", "51.5187,-0.0991", "51.5203,-0.1044"]
    # Each item still contains exactly one comma (lat,lng intact).
    assert all(item.count(",") == 1 for item in pool)


