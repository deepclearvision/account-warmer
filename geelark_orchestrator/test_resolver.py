# ---------- Provisioning / maps_verified gate (Section 9.10) ----------

def test_provisioned_false_blocks_run():
    p = profile_from_row(_row(provisioned="false", maps_verified="true"))
    fit, reason = check_phone_fit(p)
    assert fit is False
    assert "not provisioned" in reason
    assert p.profile_key in reason


def test_maps_verified_false_blocks_run():
    p = profile_from_row(_row(provisioned="true", maps_verified="false"))
    fit, reason = check_phone_fit(p)
    assert fit is False
    assert "maps not verified" in reason
    assert "Play Store" in reason  # behaviour-based warning
    assert p.profile_key in reason


def test_both_provisioned_and_maps_verified_allows_run():
    p = profile_from_row(_row(provisioned="true", maps_verified="true"))
    fit, reason = check_phone_fit(p)
    assert fit is True
    assert reason == ""


def test_provisioning_fields_parse_from_csv():
    header = "profile_key,geelark_profile_id,business_name,home_lat,home_lng,business_lat,business_lng,nearby_points,nearby_points_backup,branded_keywords,search_keywords,business_goal,profile_verdict,provisioned,maps_verified\n"
    csv = header + "Prov_01,GL-1,Biz A,51.5,-0.12,51.501,-0.088,,,,,review,pending,true,false\n"
    path = _write_temp_csv(csv)
    try:
        p = load_profile_csv_by_key(path, "Prov_01")
        assert p.provisioned is True
        assert p.maps_verified is False
    finally:
        os.unlink(path)


