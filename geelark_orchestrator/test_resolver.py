def test_exactly_one_match_succeeds():
    header = "profile_key,geelark_profile_id,business_name,home_lat,home_lng,business_lat,business_lng,nearby_points,nearby_points_backup,branded_keywords,search_keywords,business_goal,profile_verdict\n"
